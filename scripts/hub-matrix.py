#!/usr/bin/env python3
"""Renders the Hub API compatibility matrix page from the compat suite's results.

compat/hf writes compat/hf/compatibility-matrix.json when run with
HANGAR_HF_WRITE_MATRIX=1. This turns it into
docs/reference/hub-api-compatibility.md.

Run: python3 scripts/hub-matrix.py [matrix.json]
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "compat/hf/compatibility-matrix.json"
OUT = ROOT / "docs/reference/hub-api-compatibility.md"

LABEL = {"supported": "Supported", "partial": "Partial", "not supported": "Not supported"}


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render(m):
    rows = sorted(m["endpoints"].items(), key=lambda kv: (kv[0].split(" ", 1)[-1], kv[0]))
    counts = {}
    for _, v in rows:
        counts[v["status"]] = counts.get(v["status"], 0) + 1
    out = [
        "# Hub API compatibility matrix",
        "",
        "<!-- Generated by scripts/hub-matrix.py from compat/hf/compatibility-matrix.json. Do not edit; run `make generate`. -->",
        "",
        "Every Hugging Face Hub endpoint that `huggingface_hub` and the libraries built on it call, and whether Hangar serves it. "
        "The compatibility suite in `compat/hf` writes this table from its own results, so every row marked supported is covered by a passing test against real clients.",
        "",
        f"Tested with `huggingface_hub` {m.get('huggingface_hub', 'unknown')}. "
        + ", ".join(f"{n} {LABEL.get(s, s).lower()}" for s, n in sorted(counts.items())) + ".",
        "",
        "| Endpoint | Status | Covered by | Notes |",
        "|---|---|---|---|",
    ]
    for ep, v in rows:
        tests = ", ".join(f"`{t}`" for t in v.get("tests", [])) or "-"
        out.append(f"| `{cell(ep)}` | {LABEL.get(v['status'], v['status'])} | {tests} | {cell(v.get('note', ''))} |")
    out += ["", "Spaces, the Inference API, Jobs, buckets, kernels and Xet downloads are out of scope for Hangar 1.0; see [What Hangar is](../index.md).", ""]
    return "\n".join(out)


if __name__ == "__main__":
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    if not src.exists():
        print(f"{src} does not exist; run the compat/hf suite with HANGAR_HF_WRITE_MATRIX=1 first. Keeping {OUT.relative_to(ROOT)}.")
        sys.exit(0)
    OUT.write_text(render(json.loads(src.read_text())))
    print("wrote", OUT.relative_to(ROOT))
