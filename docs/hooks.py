"""MkDocs hooks: publish api/openapi.yaml next to the native API page, give
every page a description for search results, date every page from its git
history, and give every page the metadata search engines and link previews
read."""

import datetime
import html
import json
import logging
import pathlib
import re
import subprocess

from mkdocs.exceptions import PluginError
from mkdocs.structure.files import File

ROOT = pathlib.Path(__file__).resolve().parent.parent
log = logging.getLogger("mkdocs.hooks")

# A page's date is the date of the last commit that changed its source or a
# file it shows: files it includes with pymdownx.snippets (--8<-- "FILE"),
# and those listed here. The sitemap's <lastmod> and the TechArticle's
# dateModified use it, so search engines see when a page last changed, not
# when the site was last built.
EXTRA_SOURCES = {"reference/native-api.md": ["api/openapi.yaml"]}
SNIPPET = re.compile(r'^--8<--\s+"([^":]+)', re.MULTILINE)
# Paths outside docs/ that pages include or show.
INCLUDED_PATHS = ["CHANGELOG.md", "CONTRIBUTING.md", "SECURITY.md", "LICENSE", "api/openapi.yaml"]

# Path, relative to ROOT, to the date of the last commit that changed it.
# Filled by on_config for each build.
COMMIT_DATES = {}

# Search engines show a page's description under its title, so each page needs
# its own: without one, every page gets site_description. Written pages set it
# in their front matter. These pages are generated by commands that also print
# to a terminal (make generate), so their descriptions are here.
GENERATED_DESCRIPTIONS = {
    "reference/configuration.md": "Every Hangar configuration key, with its environment variable, type, default and description, for YAML files, environment variables and flags.",
    "reference/cli.md": "Every hangar command and flag, for the server, the client and admin work, with exit codes. Generated from the binary.",
    "reference/metrics.md": "Every metric Hangar exports over OTLP or on /metrics for Prometheus, with its type, unit, attributes and description.",
    "reference/hub-api-compatibility.md": "Every Hugging Face Hub API endpoint that huggingface_hub calls and whether Hangar serves it, from the compatibility suite's own results.",
}

# Google shows about 160 characters; shorter than 70 says too little.
DESCRIPTION_LENGTH = range(70, 161)

# Google shows about 60 characters of a title. A title in a page's front
# matter replaces the nav label in the page's <title> only, so it can name
# what people search for while the nav stays short. Material appends the
# site name.
TITLE_SUFFIX = " - Hangar"
TITLE_LENGTH = 60

# The home page's image, and the entity its JSON-LD describes, which every
# docs page names as its publisher (deploy/cloudflare/docs-root/index.html).
OG_IMAGE = "https://hangar.page/og.png"
HOME = "https://hangar.page/"
PUBLISHER = {"@type": "Organization", "@id": HOME + "#organization", "name": "Hangar", "url": HOME}


def on_config(config, **kwargs):
    COMMIT_DATES.clear()
    COMMIT_DATES.update(commit_dates())
    return config


def commit_dates():
    """Reads, from git, the date of the last commit that changed each file
    under docs/ and each of INCLUDED_PATHS, as YYYY-MM-DD in UTC. Files with
    uncommitted changes are left out, so they get the build date. Returns
    nothing outside a git checkout, or in a shallow clone, where every file
    would get the date of the one commit fetched: the docs workflows that
    publish the site fetch the full history (.github/workflows/docs.yml and
    release.yml)."""
    paths = ["docs", *INCLUDED_PATHS]

    def git(*args):
        return subprocess.run(
            ["git", "-C", str(ROOT), "-c", "core.quotepath=off", *args],
            capture_output=True, text=True, check=True,
        ).stdout

    try:
        if git("rev-parse", "--is-shallow-repository").strip() != "false":
            log.info("Shallow git clone: pages are dated with the build date")
            return {}
        history = git("log", "--format=%x00%ct", "--name-only", "--", *paths)
        changed = set(git("diff", "--name-only", "HEAD", "--", *paths).splitlines())
    except (OSError, subprocess.CalledProcessError):
        log.info("No git history: pages are dated with the build date")
        return {}
    dates = {}
    for entry in history.split("\x00")[1:]:
        lines = entry.strip().splitlines()
        if not lines:
            continue
        day = datetime.datetime.fromtimestamp(int(lines[0]), datetime.timezone.utc).date().isoformat()
        for path in lines[1:]:
            if path and path not in changed:
                # git log lists the newest commit first.
                dates.setdefault(path, day)
    return dates


def page_date(page, markdown):
    """The date of the last commit that changed the page or a file it shows,
    or None if any of them has no committed date (a new or changed file),
    in which case the page keeps the build date."""
    sources = ["docs/" + page.file.src_uri]
    sources += SNIPPET.findall(markdown)
    sources += EXTRA_SOURCES.get(page.file.src_uri, [])
    dates = [COMMIT_DATES.get(s) for s in sources]
    if not COMMIT_DATES or None in dates:
        return None
    return max(dates)


def on_files(files, config, **kwargs):
    files.append(File.generated(config, "reference/openapi.yaml", abs_src_path=str(ROOT / "api" / "openapi.yaml")))
    return files


def on_page_markdown(markdown, page, **kwargs):
    path = page.file.src_uri
    description = page.meta.get("description") or GENERATED_DESCRIPTIONS.get(path)
    if not description:
        raise PluginError(f"{path} has no description: add one to its front matter")
    if len(description) not in DESCRIPTION_LENGTH:
        raise PluginError(f"{path}: the description is {len(description)} characters, want 70 to 160")
    page.meta["description"] = description
    title = page.meta.get("title")
    if title and len(title + TITLE_SUFFIX) > TITLE_LENGTH:
        raise PluginError(f'{path}: the title "{title}{TITLE_SUFFIX}" is over {TITLE_LENGTH} characters')
    # MkDocs sets update_date to the build date, and the sitemap's <lastmod>
    # reads it.
    date = page_date(page, markdown)
    if date:
        page.update_date = date
    return markdown


def on_post_page(output, page, config, **kwargs):
    """Adds Open Graph and Twitter tags for link previews, and JSON-LD with the
    page's breadcrumb trail. Canonical URLs come from site_url, which mike sets
    to the canonical version (mkdocs.yml), as Material's canonical link does."""
    title = (page.meta.get("title") or page.title or config["site_name"]) + TITLE_SUFFIX
    if page.is_homepage and not page.meta.get("title"):
        title = config["site_name"]
    url = page.canonical_url
    tags = [
        ("property", "og:type", "website" if page.is_homepage else "article"),
        ("property", "og:site_name", config["site_name"]),
        ("property", "og:locale", "en_GB"),
        ("property", "og:url", url),
        ("property", "og:title", title),
        ("property", "og:description", page.meta["description"]),
        ("property", "og:image", OG_IMAGE),
        ("property", "og:image:width", "1200"),
        ("property", "og:image:height", "630"),
        ("name", "twitter:card", "summary_large_image"),
    ]
    head = "".join(f'<meta {attr}="{key}" content="{html.escape(value)}">' for attr, key, value in tags)
    head += '<script type="application/ld+json">' + json.dumps(structured_data(page, url), ensure_ascii=False).replace("</", "<\\/") + "</script>"
    return output.replace("</head>", head + "</head>", 1)


def structured_data(page, url):
    """A TechArticle for the page and, below the docs home, a BreadcrumbList
    from the home page through each section that has an index page."""
    article = {
        "@type": "TechArticle",
        "headline": page.meta.get("title") or page.title,
        "description": page.meta["description"],
        "url": url,
        "mainEntityOfPage": url,
        "inLanguage": "en-GB",
        "dateModified": page.update_date,
        "image": OG_IMAGE,
        "isPartOf": {"@type": "WebSite", "@id": HOME + "#website", "name": "Hangar", "url": HOME},
        "author": PUBLISHER,
        "publisher": PUBLISHER,
    }
    graph = [article]
    if not page.is_homepage:
        trail = [("Hangar", HOME)]
        if homepage_url(page) != HOME:
            trail.append(("Documentation", homepage_url(page)))
        for section in reversed(page.ancestors):
            index = section.children[0] if section.children else None
            if getattr(index, "is_index", False) and index is not page:
                trail.append((section.title, index.canonical_url))
        trail.append((page.title, url))
        graph.append({
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": i, "name": name, "item": item}
                for i, (name, item) in enumerate(trail, 1)
            ],
        })
    return {"@context": "https://schema.org", "@graph": graph}


def homepage_url(page):
    """The docs home page's canonical URL: the page's own, less its path."""
    return page.canonical_url[: len(page.canonical_url) - len(page.url)] if page.url else page.canonical_url
