package config

import (
	"fmt"
	"io"
	"reflect"
	"strings"
)

// WriteReference writes the configuration reference as a Markdown page:
// every key with its environment variable, type, default and description.
// `hangar config reference` prints it, and the docs page is generated from it.
func WriteReference(w io.Writer) error {
	var b strings.Builder
	b.WriteString("# Configuration reference\n\n")
	b.WriteString("<!-- Generated by `hangar config reference`. Do not edit by hand. -->\n\n")
	b.WriteString("Hangar reads its configuration from a YAML file (`hangar server --config hangar.yaml`, or the `HANGAR_CONFIG` environment variable), then from `HANGAR_*` environment variables, then from `--set key=value` flags. Later sources win. Hangar checks the whole configuration on start and reports every problem at once.\n\n")
	b.WriteString("Every key is also an environment variable: `storage.s3.bucket` is `HANGAR_STORAGE_S3_BUCKET`. List values in environment variables and flags are comma-separated. `oidc.providers` takes a JSON array.\n\n")
	b.WriteString("Sizes accept a number of bytes or a unit such as `KiB`, `MiB`, `GiB` or `GB`. Durations use Go syntax, such as `90s`, `30m` or `720h`.\n\n")

	section := ""
	fields := Fields()
	for i, f := range fields {
		if top := topKey(f.Key); top != section {
			section = top
			fmt.Fprintf(&b, "## `%s`\n\n", section)
			if d := sectionDescription(section); d != "" {
				b.WriteString(d + "\n\n")
			}
			b.WriteString("| Key | Type | Default | Description |\n|---|---|---|---|\n")
		}
		def := f.Default
		if f.Secret && def != `""` {
			def = "(secret)"
		}
		key := "`" + f.Key + "`"
		if f.Env != "" {
			key += "<br>`" + f.Env + "`"
		}
		if def != "" {
			def = "`" + escapeCell(def) + "`"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", key, f.Type, def, escapeCell(f.Description))
		if i == len(fields)-1 || topKey(fields[i+1].Key) != section {
			b.WriteString("\n")
		}
	}
	_, err := io.WriteString(w, strings.TrimRight(b.String(), "\n")+"\n")
	return err
}

func escapeCell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func sectionDescription(section string) string {
	for _, f := range topLevelFields() {
		if f.key == section {
			return f.desc
		}
	}
	return ""
}

func topKey(key string) string {
	top, _, _ := strings.Cut(key, ".")
	return top
}

type topField struct{ key, desc string }

func topLevelFields() []topField {
	var out []topField
	t := reflect.TypeFor[Config]()
	for i := range t.NumField() {
		sf := t.Field(i)
		out = append(out, topField{key: sf.Tag.Get("koanf"), desc: sf.Tag.Get("desc")})
	}
	return out
}
