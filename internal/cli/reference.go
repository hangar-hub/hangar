// referenceCommand prints the generated CLI and metrics references that the
// documentation site includes (docs/reference/cli.md and metrics.md).
func referenceCommand(root *cobra.Command) *cobra.Command {
	cmd := &cobra.Command{
		Use:    "reference",
		Short:  "Print generated reference pages for the documentation",
		Hidden: true,
		Args:   args(cobra.NoArgs),
	}
	cmd.AddCommand(&cobra.Command{
		Use:   "cli",
		Short: "Print the CLI reference in Markdown",
		Args:  args(cobra.NoArgs),
		RunE: func(cmd *cobra.Command, _ []string) error {
			return WriteCLIReference(cmd.OutOrStdout(), root)
		},
	}, &cobra.Command{
		Use:   "metrics",
		Short: "Print the metrics reference in Markdown",
		Args:  args(cobra.NoArgs),
		RunE: func(cmd *cobra.Command, _ []string) error {
			return WriteMetricsReference(cmd.OutOrStdout())
		},
	})
	return cmd
}

// WriteCLIReference writes every visible command under root as Markdown.
func WriteCLIReference(w io.Writer, root *cobra.Command) error {
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	var b strings.Builder
	b.WriteString("# CLI reference\n\n")
	b.WriteString("<!-- Generated by `hangar reference cli`. Do not edit; run `make generate`. -->\n\n")
	b.WriteString("`hangar` is one binary for the server and the client. Client commands talk to an Instance through the Hub API and the native API; admin commands work on an Instance's database and Blob store directly.\n\n")
	b.WriteString("Every client command takes `--url`, `--token` and `--json`. Without `--url` and `--token`, they use the login saved by `hangar login`, or the `HANGAR_CLI_URL` and `HANGAR_CLI_TOKEN` environment variables.\n\n")
	b.WriteString("## Exit codes\n\n| Code | Meaning |\n|---|---|\n| 0 | Success. |\n| 1 | An error. |\n| 2 | A usage error, such as a missing argument or an unknown flag. |\n| 3 | Not found, such as a Repo or a file. |\n| 4 | An authentication error: not signed in, or the Token is not allowed. |\n\n")
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		if c != root {
			writeCommand(&b, c)
		}
		subs := c.Commands()
		sort.Slice(subs, func(i, j int) bool { return subs[i].Name() < subs[j].Name() })
		for _, s := range subs {
			if s.Hidden || s.Name() == "help" || s.Name() == "completion" {
				continue
			}
			walk(s)
		}
	}
	walk(root)
	_, err := io.WriteString(w, b.String())
	return err
}

func writeCommand(b *strings.Builder, c *cobra.Command) {
	fmt.Fprintf(b, "## %s\n\n", c.CommandPath())
	if c.Short != "" {
		fmt.Fprintf(b, "%s.\n\n", strings.TrimSuffix(c.Short, "."))
	}
	if c.Long != "" {
		fmt.Fprintf(b, "```text\n%s\n```\n\n", strings.TrimSpace(c.Long))
	}
	if c.Runnable() {
		fmt.Fprintf(b, "Usage:\n\n```sh\n%s\n```\n\n", c.UseLine())
	}
	if c.Example != "" {
		fmt.Fprintf(b, "Examples:\n\n```sh\n%s\n```\n\n", trimIndent(c.Example))
	}
	if subs := visibleSubcommands(c); len(subs) > 0 {
		b.WriteString("Subcommands:\n\n")
		for _, s := range subs {
			fmt.Fprintf(b, "- [`%s`](#%s): %s\n", s.CommandPath(), anchor(s.CommandPath()), s.Short)
		}
		b.WriteString("\n")
	}
	writeFlags(b, "Flags", c.NonInheritedFlags())
	writeFlags(b, "Inherited flags", c.InheritedFlags())
}

func visibleSubcommands(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, s := range c.Commands() {
		if !s.Hidden && s.Name() != "help" && s.Name() != "completion" {
			out = append(out, s)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name() < out[j].Name() })
	return out
}

func writeFlags(b *strings.Builder, title string, fs *pflag.FlagSet) {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "`--" + f.Name + "`"
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		def := f.DefValue
		switch def {
		case "", "[]", "false", "0":
			def = ""
		default:
			def = "`" + def + "`"
		}
		usage := strings.ReplaceAll(f.Usage, "|", `\|`)
		rows = append(rows, fmt.Sprintf("| %s | %s | %s |", name, usage, def))
	})
	if len(rows) == 0 {
		return
	}
	fmt.Fprintf(b, "%s:\n\n| Flag | Description | Default |\n|---|---|---|\n%s\n\n", title, strings.Join(rows, "\n"))
}

// anchor returns the MkDocs heading anchor for a command path.
func anchor(s string) string {
	return strings.ReplaceAll(strings.ToLower(s), " ", "-")
}

// trimIndent removes the common two-space indent cobra examples use.
func trimIndent(s string) string {
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimPrefix(l, "  ")
	}
	return strings.Join(lines, "\n")
}

