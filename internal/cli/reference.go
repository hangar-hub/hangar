// instrumentInfo is one instrument recorded by recordingMeter.
type instrumentInfo struct {
	Name, Kind, Unit, Description string
}

// recordingMeter records the instruments created on it.
type recordingMeter struct {
	noop.Meter
	got []instrumentInfo
}

func (m *recordingMeter) add(name, kind, unit, desc string) {
	m.got = append(m.got, instrumentInfo{Name: name, Kind: kind, Unit: unit, Description: desc})
}

func (m *recordingMeter) Int64Counter(name string, opts ...metric.Int64CounterOption) (metric.Int64Counter, error) {
	c := metric.NewInt64CounterConfig(opts...)
	m.add(name, "counter", c.Unit(), c.Description())
	return m.Meter.Int64Counter(name, opts...)
}

func (m *recordingMeter) Float64Counter(name string, opts ...metric.Float64CounterOption) (metric.Float64Counter, error) {
	c := metric.NewFloat64CounterConfig(opts...)
	m.add(name, "counter", c.Unit(), c.Description())
	return m.Meter.Float64Counter(name, opts...)
}

func (m *recordingMeter) Int64Gauge(name string, opts ...metric.Int64GaugeOption) (metric.Int64Gauge, error) {
	c := metric.NewInt64GaugeConfig(opts...)
	m.add(name, "gauge", c.Unit(), c.Description())
	return m.Meter.Int64Gauge(name, opts...)
}

func (m *recordingMeter) Float64Histogram(name string, opts ...metric.Float64HistogramOption) (metric.Float64Histogram, error) {
	c := metric.NewFloat64HistogramConfig(opts...)
	m.add(name, "histogram", c.Unit(), c.Description())
	return m.Meter.Float64Histogram(name, opts...)
}

// hangarInstruments returns every instrument internal/telemetry creates.
func hangarInstruments() ([]instrumentInfo, error) {
	m := &recordingMeter{}
	if _, err := telemetry.NewInstruments(m); err != nil {
		return nil, err
	}
	return m.got, nil
}

// prometheusName returns the name the Prometheus exporter gives an
// instrument: dots become underscores, plus the unit and _total suffixes.
func prometheusName(i instrumentInfo) string {
	n := strings.ReplaceAll(i.Name, ".", "_")
	switch i.Unit {
	case "By":
		if !strings.HasSuffix(n, "_bytes") {
			n += "_bytes"
		}
	case "s":
		if !strings.HasSuffix(n, "_seconds") {
			n += "_seconds"
		}
	}
	if i.Kind == "counter" {
		n += "_total"
	}
	return n
}

// WriteMetricsReference writes the metrics reference as Markdown.
func WriteMetricsReference(w io.Writer) error {
	ins, err := hangarInstruments()
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# Metrics reference\n\n")
	b.WriteString("<!-- Generated by `hangar reference metrics`. Do not edit; run `make generate`. -->\n\n")
	b.WriteString("Hangar exports these metrics over OTLP, or on `/metrics` when `telemetry.metrics` is `prometheus`. HTTP server and client metrics follow the OpenTelemetry semantic conventions (`http.server.request.duration`, `http.server.active_requests` and the body size histograms), and Go runtime metrics come from the runtime instrumentation. Repo IDs are never metric attributes; they are on spans and logs.\n\n")
	b.WriteString("Gauges that need a database count are computed by one worker at a time every 60 seconds.\n\n")
	b.WriteString("| Metric | Prometheus name | Type | Unit | Attributes | Description |\n|---|---|---|---|---|---|\n")
	for _, i := range ins {
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | `%s` | %s | %s |\n", i.Name, prometheusName(i), i.Kind, i.Unit, orDash(metricAttributes[i.Name]), i.Description)
	}
	_, err = io.WriteString(w, b.String())
	return err
}
