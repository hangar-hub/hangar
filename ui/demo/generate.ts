import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadSpec, standaloneValidators } from "../mock/openapi.ts";

/**
 * Writes the demo Worker's entry point to demo/gen: the parsed api/openapi.yaml
 * and its validators compiled ahead of time, because Workers cannot compile
 * code at run time, as Ajv does in `vite preview`. wrangler.jsonc names
 * gen/index.js as the Worker's main module.
 *
 * Usage: node demo/generate.ts (make demo runs it).
 */

const out = fileURLToPath(new URL("./gen/", import.meta.url));
mkdirSync(out, { recursive: true });
const { doc } = loadSpec();
writeFileSync(`${out}spec.json`, JSON.stringify(doc));
writeFileSync(`${out}validators.js`, standaloneValidators(doc));
writeFileSync(
  `${out}index.js`,
  `// Generated by demo/generate.ts. Do not edit.
import doc from "./spec.json";
import * as validators from "./validators.js";
import { compiledValidators, createDemoWorker } from "../worker.ts";

export default createDemoWorker(doc, compiledValidators(validators));
`,
);
console.log(`Wrote the demo Worker's spec and validators to ${out}`);
