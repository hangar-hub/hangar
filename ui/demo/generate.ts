import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadSpec, standaloneValidators } from "../mock/openapi.ts";

/**
 * Writes the demo Worker's entry point to demo/gen: the parsed api/openapi.yaml
 * and its validators compiled ahead of time, because Workers cannot compile
 * code at run time, as Ajv does in `vite preview`, and the files the Worker
 * serves at its root (worker.ts RootFiles), which hangar.page serves from
 * deploy/cloudflare/docs-root.
 * wrangler.jsonc names gen/index.js as the Worker's main module.
 *
 * Usage: node demo/generate.ts (make demo runs it).
 */

/**
 * The files Google Search Console and Bing Webmaster Tools issued for
 * hangar.page and demo.hangar.page, and the raster favicons, by content type.
 */
const rootFiles: Record<string, string> = {
  "google7049fba5ad0480df.html": "text/html; charset=utf-8",
  "BingSiteAuth.xml": "application/xml",
  "favicon.ico": "image/x-icon",
  "favicon-96.png": "image/png",
};

const out = fileURLToPath(new URL("./gen/", import.meta.url));
const docsRoot = fileURLToPath(new URL("../../deploy/cloudflare/docs-root/", import.meta.url));
mkdirSync(out, { recursive: true });
const { doc } = loadSpec();
writeFileSync(`${out}spec.json`, JSON.stringify(doc));
writeFileSync(`${out}validators.js`, standaloneValidators(doc));
const files = Object.fromEntries(
  Object.entries(rootFiles).map(([name, type]) => [
    `/${name}`,
    { type, body: readFileSync(`${docsRoot}${name}`).toString("base64") },
  ]),
);
writeFileSync(`${out}root-files.json`, JSON.stringify(files));
writeFileSync(
  `${out}index.js`,
  `// Generated by demo/generate.ts. Do not edit.
import doc from "./spec.json";
import * as validators from "./validators.js";
import rootFiles from "./root-files.json";
import { compiledValidators, createDemoWorker } from "../worker.ts";

export default createDemoWorker(doc, compiledValidators(validators), rootFiles);
`,
);
console.log(`Wrote the demo Worker's spec, validators and root files to ${out}`);
