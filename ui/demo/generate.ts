import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadSpec, standaloneValidators } from "../mock/openapi.ts";

/**
 * Writes the demo Worker's entry point to demo/gen: the parsed api/openapi.yaml
 * and its validators compiled ahead of time, because Workers cannot compile
 * code at run time, as Ajv does in `vite preview`, and the search engines'
 * verification files, which hangar.page serves from deploy/cloudflare/docs-root.
 * wrangler.jsonc names gen/index.js as the Worker's main module.
 *
 * Usage: node demo/generate.ts (make demo runs it).
 */

/** The files Google Search Console and Bing Webmaster Tools issued for hangar.page and demo.hangar.page. */
const verificationNames = ["google7049fba5ad0480df.html", "BingSiteAuth.xml"];

const out = fileURLToPath(new URL("./gen/", import.meta.url));
const docsRoot = fileURLToPath(new URL("../../deploy/cloudflare/docs-root/", import.meta.url));
mkdirSync(out, { recursive: true });
const { doc } = loadSpec();
writeFileSync(`${out}spec.json`, JSON.stringify(doc));
writeFileSync(`${out}validators.js`, standaloneValidators(doc));
const verification = Object.fromEntries(
  verificationNames.map((name) => [`/${name}`, readFileSync(`${docsRoot}${name}`, "utf8")]),
);
writeFileSync(`${out}verification.json`, JSON.stringify(verification));
writeFileSync(
  `${out}index.js`,
  `// Generated by demo/generate.ts. Do not edit.
import doc from "./spec.json";
import * as validators from "./validators.js";
import verification from "./verification.json";
import { compiledValidators, createDemoWorker } from "../worker.ts";

export default createDemoWorker(doc, compiledValidators(validators), verification);
`,
);
console.log(`Wrote the demo Worker's spec, validators and verification files to ${out}`);
